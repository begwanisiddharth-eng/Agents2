import sqlite3
import json
from dotenv import load_dotenv

load_dotenv(override=True)

DB = "accounts.db"

with sqlite3.connect(DB) as Conn:
    Cursor = Conn.cursor()
    Cursor.execute("CREATE TABLE IF NOT EXISTS accounts (name TEXT PRIMARY KEY, account TEXT)")
    Cursor.execute(
        '''
        CREATE TABLE IF NOT EXISTS logs (
            id INTEGER PRIMARY KEY AUTOINCREMENT, 
            name TEXT,
            datetime DATETIME,
            type TEXT,
            message TEXT
        )
        '''
    )
    Conn.commit()

## The below function stores one trader's whole account as a single row in the account table. The
## row holds a name and one text column containing the account as JSON. AccountDict is a nested
## dictionary which is generated by the model_dump() function of Account class instance. The json.dumps
## function turns it into one string. It converts tuples in the nested dictionary into lists in the string.
## When ReadAccount is called later, json.loads gives a list which is fine here, because Pydantic 
## converts it into a tuple again when Account(**Fields) is built.
## ON CONFLICT(name) DO UPDATE. This is an upsert. name is the PRIMARY KEY, so the first call for a trader 
## inserts a row. Later calls hit the conflict and instead replace the account column. excluded.account means 
##"the value I was trying to insert".

def WriteAccount(Name, AccountDict):
    JSONData = json.dumps(AccountDict)
    with sqlite3.connect(DB) as Conn:
        Cursor = Conn.cursor()
        Cursor.execute(
            '''
            INSERT INTO accounts(name, account)
            VALUES (?,?)
            ON CONFLICT(name) DO UPDATE SET account=excluded.account
            ''', (Name.lower(),JSONData))
        Conn.commit()

def ReadAccount(Name):
    with sqlite3.connect(DB) as Conn:
        Cursor = Conn.cursor()
        Cursor.execute('SELECT account from accounts WHERE name = ?',(Name.lower(),))
        Row = Cursor.fetchone()
        return json.loads(Row[0]) if Row else None

def WriteLog(Name: str, Type: str, Message: str):
    """
    Write a log entry to the logs table

    Args:
        Name (str): The name associated with the log
        Type (str): The type of log entry
        Message (str): The log message
    """
    ## SQLite has a built-in datetime(time-value, modifier, ...) function. The argument 'now' is a keyword
    ## that means the current moment. The function returns the current date and time as a text string in 
    ## the form YYYY-MM-DD HH:MM:SS and it returns the UTC time. To return the local time, the modifier 'localtime'
    ## can be used
    with sqlite3.connect(DB) as Conn:
        Cursor = Conn.cursor()
        Cursor.execute(
            '''
            INSERT INTO logs(name,datetime,type,message)
            VALUES (?, datetime('now'), ?, ?)
            ''', (Name.lower(), Type, Message)
        )
        Conn.commit()

def ReadLog(Name: str, LastN:int=10):
    """
    Read the most recent log entries for a given name

    Args:
        Name (str): The name to retrieve logs for
        LastN (int): The number of latest entries to retrieve
    Returns:
        A list of tuples containing (datetime, type, message)
    """
    with sqlite3.connect(DB) as Conn:
        Cursor = Conn.cursor()
        Cursor.execute(
            '''
            SELECT datetime, type, message FROM logs
            WHERE name = ?
            ORDER BY datetime DESC
            LIMIT ?
            ''', (Name.lower(),LastN))
        return reversed(Cursor.fetchall())